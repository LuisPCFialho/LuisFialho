        const setLanguage = (lang) => {
            const elements = document.querySelectorAll('[data-translate]');
            elements.forEach(el => {
                const key = el.getAttribute('data-translate');
                if (translations[lang] && translations[lang][key]) {
                    el.innerHTML = translations[lang][key];
                }
            });
            document.documentElement.lang = lang;
            localStorage.setItem('language', lang);

            // Update flag emoji
            const emojiMap = { pt: '🇵🇹', en: '🇬🇧', es: '🇪🇸', fr: '🇫🇷' };
            document.getElementById('current-lang-emoji').innerText = emojiMap[lang];

            // Re-type header subtitle and tagline with translated text
            if (window._retypeHeader && translations[lang]) {
                window._retypeHeader(
                    translations[lang].header_subtitle || '',
                    translations[lang].header_tagline || ''
                );
            }
        };

        // --- DARK MODE LOGIC ---
        const themeToggleBtn = document.getElementById('theme-toggle');
        const themeToggleDarkIcon = document.getElementById('theme-toggle-dark-icon');
        const themeToggleLightIcon = document.getElementById('theme-toggle-light-icon');
        const languageToggleBtn = document.getElementById('language-toggle');
        const languageMenu = document.getElementById('language-menu');
        
        // Function to toggle theme
        const toggleTheme = () => {
            themeToggleDarkIcon.classList.toggle('hidden');
            themeToggleLightIcon.classList.toggle('hidden');
            document.documentElement.classList.toggle('dark');
            const isDark = document.documentElement.classList.contains('dark');
            localStorage.setItem('color-theme', isDark ? 'dark' : 'light');
        };

        // Initial theme setup
        if (localStorage.getItem('color-theme') === 'dark' || (!('color-theme' in localStorage) && window.matchMedia('(prefers-color-scheme: dark)').matches)) {
            document.documentElement.classList.add('dark');
            themeToggleLightIcon.classList.remove('hidden');
        } else {
            themeToggleDarkIcon.classList.remove('hidden');
        }
        
        // Theme toggle button event
        themeToggleBtn.addEventListener('click', toggleTheme);

        // --- LANGUAGE SWITCHER LOGIC ---
        // Toggle language menu
        languageToggleBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            languageMenu.classList.toggle('hidden');
        });
        
        // Close menu if clicking outside
        document.addEventListener('click', () => {
             if (!languageMenu.classList.contains('hidden')) {
                languageMenu.classList.add('hidden');
             }
        });

        // Language selection event
        languageMenu.addEventListener('click', (e) => {
            const lang = e.target.closest('a').dataset.lang;
            if (lang) {
                setLanguage(lang);
                languageMenu.classList.add('hidden');
            }
        });

        // Initial language setup
        const initialLang = localStorage.getItem('language') || 'pt';
        setLanguage(initialLang);
        
        // --- SCROLL ANIMATION LOGIC ---
        const sections = document.querySelectorAll('.fade-in-section');
        const observer = new IntersectionObserver(entries => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                }
            });
        }, {
            threshold: 0.1
        });

        sections.forEach(section => {
            observer.observe(section);
        });
